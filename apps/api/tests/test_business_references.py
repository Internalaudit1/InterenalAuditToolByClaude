def _ensure_user(db: Session, *, username: str, role_code: str, email: str, full_name: str) -> None:
    if user_service.get_by_username(db, username):
        return
    designation_id = db.scalar(select(Designation.id).where(Designation.code == "AUD").limit(1))
    company_id = db.scalar(select(Company.id).limit(1))
    location_id = db.scalar(select(Location.id).limit(1))
    user_service.create_user(
        db,
        UserCreate(
            username=username,
            email=email,
            full_name=full_name,
            password="Password@123",
            designation_id=designation_id,
            company_id=company_id,
            location_id=location_id,
            role_codes=[role_code],
        ),
        "test",
    )
    db.commit()


def _user_id(db: Session, username: str) -> int:
    user = user_service.get_by_username(db, username)
    assert user is not None
    return user.id


def test_audit_plan_number_is_generated_and_manual_value_is_rejected(client: TestClient):
    headers = auth_headers(client, "auditoruser1")

    response = client.post("/api/v1/planning/audit-plans", json=_audit_plan_payload("Generated plan"), headers=headers)
    assert response.status_code == 200
    payload = response.json()
    assert payload["audit_number"].startswith(f"AUD-{date.today().year}-")
    assert payload["period_type"] == "Quarterly"
    assert payload["period_value"] == "Q2"
    assert payload["quarter"] == "Q2"

    manual_payload = _audit_plan_payload("Manual plan")
    manual_payload["audit_number"] = "AUD-MANUAL"
    manual_response = client.post("/api/v1/planning/audit-plans", json=manual_payload, headers=headers)
    assert manual_response.status_code == 422


