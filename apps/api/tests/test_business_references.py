def test_audits_share_plan_number_or_generate_unique_unplanned_number(client: TestClient):
    headers = auth_headers(client, "auditoruser1")
    plan_response = client.post("/api/v1/planning/audit-plans", json=_audit_plan_payload("Linked plan"), headers=headers)
    assert plan_response.status_code == 200
    plan_payload = plan_response.json()

    linked_response = client.post(
        "/api/v1/audits",
        json=_audit_payload("Linked execution", audit_plan_id=plan_payload["id"]),
        headers=headers,
    )
    assert linked_response.status_code == 200
    assert linked_response.json()["audit_number"] == plan_payload["audit_number"]

    unplanned_response = client.post(
        "/api/v1/audits",
        json=_audit_payload("Unplanned execution", planned_flag=False),
        headers=headers,
    )
    assert unplanned_response.status_code == 200
    assert unplanned_response.json()["audit_number"].startswith(f"AUD-{date.today().year}-")
    assert unplanned_response.json()["audit_number"] != plan_payload["audit_number"]

    manual_payload = _audit_payload("Manual audit")
    manual_payload["audit_number"] = "AUD-MANUAL"
    manual_response = client.post("/api/v1/audits", json=manual_payload, headers=headers)
    assert manual_response.status_code == 422


def test_action_plan_references_are_generated_and_manual_values_are_rejected(client: TestClient):
    headers = auth_headers(client, "auditoruser1")

    response = client.post("/api/v1/action-plans", json=_action_plan_payload(1), headers=headers)
    assert response.status_code == 200
    payload = response.json()
    assert payload["action_plan_id"].startswith(f"ACT-{date.today().year}-")
    assert payload["observation_number"].startswith(f"OBS-{date.today().year}-")
    assert payload["audit_number"].startswith("AUD-")

    manual_payload = _action_plan_payload(1)
    manual_payload["audit_number"] = "AUD-MANUAL"
    manual_payload["action_plan_id"] = "ACT-MANUAL"
    manual_payload["observation_number"] = "OBS-MANUAL"
    manual_response = client.post("/api/v1/action-plans", json=manual_payload, headers=headers)
    assert manual_response.status_code == 422

    update_response = client.put(
        f"/api/v1/action-plans/{payload['id']}",
        json={"observation_number": "OBS-UPDATED"},
        headers=headers,
    )
    assert update_response.status_code == 422
